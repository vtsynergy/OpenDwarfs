#!/bin/bash
# =============================================================================
# OpenACC toolchain via the site-provided NVIDIA HPC SDK module (no download).
#   milan2: /opt/nvidia/hpc_sdk/Linux_x86_64/25.5, `module load nvhpc/25.5`
#           (bundled CUDA 12.9 -> supports Volta sm_70)
#
# This script verifies the module and writes $ACC_PREFIX/env.sh, which every
# openacc build/run script sources, so $ACC_PREFIX (~/.local/apps/openacc-<host>)
# is the single entry point even though the compilers live in /opt.
#
# HOW TO MODIFY
#   other version : NVHPC_VER=25.9 ./install-openacc-nvhpc-module.sh
#                   (`module avail nvhpc` to see what the site offers)
#   other module  : NVHPC_MODULE=nvhpc-nompi/25.5
#   no module on this machine : run install-openacc-nvhpc-download.sh instead
#   other GPU     : GPU_ARCH_SM=80 (becomes -gpu=cc80). Keep CUDA <13 for Volta.
# =============================================================================
set -euo pipefail
source "$(dirname "${BASH_SOURCE[0]}")/env.sh"
for f in /usr/share/lmod/lmod/init/bash /etc/profile.d/modules.sh /usr/share/modules/init/bash; do
  [ -r "$f" ] && { source "$f"; break; }
done
type module >/dev/null 2>&1 || { echo "No environment-modules/lmod found; use the -download script"; exit 1; }
module load "$NVHPC_MODULE"
command -v nvc >/dev/null || { echo "ERROR: nvc not found after 'module load $NVHPC_MODULE'"; exit 1; }
nvc --version | sed -n 2p
mkdir -p "$ACC_PREFIX"
cat > "$ACC_PREFIX/env.sh" <<EOT
# Generated by install-openacc-nvhpc-module.sh
for f in /usr/share/lmod/lmod/init/bash /etc/profile.d/modules.sh; do [ -r "\$f" ] && { source "\$f"; break; }; done
module load $NVHPC_MODULE
export ACC_GPU_CC=cc${GPU_ARCH_SM}
export NVHPC_CUDA_ROOT="$NVHPC_CUDA_ROOT"
EOT
echo "Wrote $ACC_PREFIX/env.sh"
